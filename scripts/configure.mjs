#!/usr/bin/env node
// Writes owner/wrangler.toml (editor) and site/wrangler.toml (live site) from client.config.json.
// Run after changing client.config.json:  npm run configure
// Secrets are NEVER written here – set them with `npx wrangler secret put …` (see docs/PLAYBOOK.md).
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateReviewsPath } from '../src/lib/core.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const c = JSON.parse(await readFile(join(root, 'client.config.json'), 'utf8'));
const cf = c.cloudflare || {};
const pathProblems = validateReviewsPath(c.reviewsPath);
if (pathProblems.length) { console.error('client.config.json: ' + pathProblems.join('; ')); process.exit(1); }
const q = (v) => JSON.stringify(String(v ?? ''));
const todo = (v, what) => (v ? q(v) : `"" # TODO: ${what}`);

const owner = `# GENERATED by scripts/configure.mjs from client.config.json – edit that file, then run \`npm run configure\`.
# Owner editor for ${c.client?.name} (Cloudflare Worker, free plan).
name = ${q(cf.editorWorker)}
main = "src/index.mjs"
compatibility_date = "2026-10-01"
workers_dev = true
${cf.accountId ? `account_id = ${q(cf.accountId)}\n` : ''}
[assets]
directory = "./ui"
binding = "ASSETS"
run_worker_first = true

[[d1_databases]]
binding = "DB"
database_name = ${q(cf.d1Name)}
database_id = ${todo(cf.d1Id, 'npx wrangler d1 create ' + cf.d1Name)}
migrations_dir = "migrations"

[[kv_namespaces]]
binding = "PHOTOS"
id = ${todo(cf.kvId, 'npx wrangler kv namespace create PHOTOS')}

[vars]
GITHUB_REPO = ${q(c.github?.repo)}
GITHUB_BRANCH = "main"
# The live website. Before launch you can point this at the GitHub Pages testing link.
PUBLIC_SITE_URL = ${q(c.domain?.main ? 'https://' + c.domain.main : '')}
ACCESS_TEAM_DOMAIN = ${todo(cf.accessTeamDomain, 'Cloudflare Zero Trust team domain')}
ACCESS_AUD = ${todo(cf.accessAud, 'Access application AUD tag')}
SUPPORT_NAME = ${q(c.owner?.supportName)}

# Secrets (set with: npx wrangler secret put NAME):
#   GITHUB_TOKEN       fine-grained token: this repo only, Contents read/write, Actions read/write
#   OWNER_EMAILS       the owner's sign-in email(s), comma-separated
#   MAINTAINER_EMAILS  your sign-in email
#   SUPPORT_EMAIL      shown to the owner as their help contact
#   SUPPORT_PHONE      (optional) shown to the owner as their help contact
`;

const site = `# GENERATED by scripts/configure.mjs from client.config.json – edit that file, then run \`npm run configure\`.
# The live website (${c.domain?.main}). Deployed by .github/workflows/live.yml on every push to main.
name = ${q(cf.siteWorker)}
main = "worker.mjs"
compatibility_date = "2026-11-01"
workers_dev = true
${cf.accountId ? `account_id = ${q(cf.accountId)}\n` : ''}
[assets]
directory = "../dist-prod"
binding = "ASSETS"
not_found_handling = "404-page"
run_worker_first = true

[vars]
MAIN_HOST = ${q(c.domain?.main)}
APEX_HOST = ${q(c.domain?.apex)}
`;
await writeFile(join(root, 'owner/wrangler.toml'), owner);
await writeFile(join(root, 'site/wrangler.toml'), site);
console.log('Wrote owner/wrangler.toml and site/wrangler.toml');
